import pandas as pd
R="data/raw/"
def vc(s): return dict(s.value_counts())
def pr(s): return dict(min=s.min(),median=s.median(),mean=round(s.mean(),1),max=s.max())
A=pd.read_csv(R+"A_bathwal/Clean_Dataset.csv")
print("### A Clean_Dataset"); 
for c in ["airline","source_city","destination_city","class","stops","departure_time"]: print(c,vc(A[c]))
print("days_left",A.days_left.min(),A.days_left.max(),"| price",pr(A.price),"| duration",pr(A.duration))
print("price by class",A.groupby("class").price.agg(["count","min","median","mean","max"]).round(0).to_dict("index"))
print("route pairs",A.groupby(["source_city","destination_city"]).ngroups,"(same-city pairs:",int((A.source_city==A.destination_city).sum()),")")
k=["airline","flight","source_city","destination_city","class"]
g=A.groupby(k); print("flight-route-class series:",g.ngroups,"| rows/series median",g.size().median(),"max",g.size().max())
print("rows duplicated on all-but-price+index:",int(A.drop(columns=["Unnamed: 0","price"]).duplicated().sum()))
print("rows sharing (series,days_left) with another row, differing by dep/arr/duration/stops:",int(A.duplicated(k+["days_left"],keep=False).sum()))
print("airline x class",A.groupby(["airline","class"]).size().to_dict())
# price vs days_left (describe only)
print("median price by days_left bucket",A.groupby(pd.cut(A.days_left,[0,1,3,7,14,21,30,49])).price.median().to_dict())
B=pd.read_csv(R+"B_goibibo/goibibo_flights_data.csv").drop(columns=["Unnamed: 11","Unnamed: 12"])
print("\n### B goibibo")
d=pd.to_datetime(B["flight date"],format="%d-%m-%Y"); print("dates",d.min().date(),d.max().date(),d.nunique())
for c in ["airline","class","from","to"]: print(c,vc(B[c]))
print("stops sample",vc(B.stops.str.replace(r"\s+"," ",regex=True).str.slice(0,25)).__repr__()[:300])
p=B.price.str.replace(",","").astype(int); print("price",pr(p))
print("price by class",p.groupby(B["class"]).agg(["count","min","median","max"]).to_dict("index"))
print("flight_num+date+class repeated:",int(B.duplicated(["flight date","flight_num","class","from","to","dep_time"],keep=False).sum()))
C=pd.read_excel(R+"C_dopodix/Data_Train.xlsx")
print("\n### C Data_Train")
for c in ["Airline","Source","Destination","Total_Stops","Additional_Info"]: print(c,vc(C[c]))
d=pd.to_datetime(C.Date_of_Journey,format="%d/%m/%Y"); print("dates",d.min().date(),d.max().date(),d.nunique(),"| price",pr(C.Price))
print("features-dup (all cols) =",int(C.duplicated().sum()),"| 'Delhi' vs 'New Delhi' dest:",vc(C.Destination))
E=pd.read_csv(R+"E_yashdharme/Cleaned_dataset.csv")
print("\n### E Cleaned_dataset")
d=pd.to_datetime(E.Date_of_journey); print("dates",d.min().date(),d.max().date(),d.nunique())
for c in ["Airline","Class","Source","Destination","Total_stops","Departure"]: print(c,vc(E[c]))
print("Days_left",E.Days_left.min(),E.Days_left.max(),"| fare",pr(E.Fare))
print("fare by class",E.groupby("Class").Fare.agg(["count","min","median","max"]).to_dict("index"))
print("source==destination:",int((E.Source==E.Destination).sum()))
